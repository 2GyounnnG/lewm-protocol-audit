#!/usr/bin/env python3
"""CPU paired-bootstrap intervals for headline AP-vs-LeWM label contrasts."""
from pathlib import Path
import csv, numpy as np, json, hashlib
ROOT=Path(__file__).resolve().parent; SRC=ROOT/'a1_results'/'A1_TRAJECTORY_SUMMARY.csv'; OUT=ROOT/'a3_results'/'revision3_pair_stats.tex'; AUD=ROOT/'a3_results'/'REV3_PAIR_STATS_AUDIT.json'
rows=list(csv.DictReader(SRC.open(encoding='utf-8-sig')))
# Held-out derived rows have 100 cases x 3 streams for each model-task.
def ci(task,metric):
    a=[r for r in rows if r['task']==task and r['model']=='M03_h1']; b=[r for r in rows if r['task']==task and r['model']=='LeWM_h1']
    A={ (r['case_id'],r['stream']):float(r[metric]) for r in a}; B={ (r['case_id'],r['stream']):float(r[metric]) for r in b}
    keys=sorted(set(A)&set(B)); cases=sorted(set(k[0] for k in keys));
    by={c:np.mean([A[(c,s)]-B[(c,s)] for cc,s in keys if cc==c]) for c in cases}
    vals=np.array([by[c] for c in cases]); est=vals.mean(); rng=np.random.default_rng(20261012)
    boot=np.empty(5000)
    for j in range(len(boot)): boot[j]=vals[rng.integers(0,len(vals),len(vals))].mean()
    return est,float(np.quantile(boot,.025)),float(np.quantile(boot,.975)),len(cases),len(keys)
res={}
for task in ['reacher','pusht','tworoom','cube']:
    anyv=ci(task,'success_any'); fin=ci(task,'success_final')
    # paired change in the same case bootstrap: construct both vectors once
    res[task]={'any':anyv,'final':fin}
    # independent helper on per-case vectors is avoided; recompute the coupled change
    a=[r for r in rows if r['task']==task and r['model']=='M03_h1']; b=[r for r in rows if r['task']==task and r['model']=='LeWM_h1']
    A={(r['case_id'],r['stream']):float(r['success_any']) for r in a}; B={(r['case_id'],r['stream']):float(r['success_any']) for r in b}; AF={(r['case_id'],r['stream']):float(r['success_final']) for r in a}; BF={(r['case_id'],r['stream']):float(r['success_final']) for r in b}; keys=sorted(set(A)&set(B)&set(AF)&set(BF)); cases=sorted(set(k[0] for k in keys));
    v=np.array([np.mean([AF[(c,s)]-BF[(c,s)]-(A[(c,s)]-B[(c,s)]) for cc,s in keys if cc==c]) for c in cases]); rng=np.random.default_rng(20261012); q=np.array([v[rng.integers(0,len(v),len(v))].mean() for _ in range(5000)]); res[task]['change']=(float(v.mean()),float(np.quantile(q,.025)),float(np.quantile(q,.975)),len(cases),len(keys))

def fmt(x): return f'{x[0]*100:+.1f} [{x[1]*100:+.1f}, {x[2]*100:+.1f}]'
def put(name,x): return f'\\newcommand{{\\{name}}}{{{fmt(x)}}}\n'
text='%% Generated by REVISION_3_PAIR_STATS.py; CPU-only.\n'
for task,label in [('reacher','Reacher'),('pusht','PushT'),('tworoom','TwoRoom'),('cube','Cube')]:
  text+=put('APLeWM'+label+'AnyCI',res[task]['any'])
  text+=put('APLeWM'+label+'FinalCI',res[task]['final'])
  text+=put('APLeWM'+label+'ChangeCI',res[task]['change'])
OUT.write_text(text,encoding='utf-8')
AUD.write_text(json.dumps({'source':str(SRC),'source_sha256':hashlib.sha256(SRC.read_bytes()).hexdigest(),'bootstrap':5000,'seed':20261012,'estimand':'case mean of stream-paired AP minus LeWM; change=(final delta)-(any delta)','results':res},ensure_ascii=False,indent=2)+'\n',encoding='utf-8')
print('wrote',OUT)
